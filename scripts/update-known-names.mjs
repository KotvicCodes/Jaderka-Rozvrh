#!/usr/bin/env node
/**
 * Regenerates src/import/known-names.ts from rozvrh.fjfi.cvut.cz: every
 * teacher listed on the department pages (/rozvrh/ucitele/<katedra>) and
 * every room code from the classroom list (/seznam-uceben).
 *
 *   node scripts/update-known-names.mjs
 */
import { writeFileSync } from 'node:fs';

const BASE = 'https://rozvrh.fjfi.cvut.cz';
const DEPARTMENTS = ['km', 'kf', 'khvj', 'kipl', 'klff', 'kmat', 'kjch', 'kdaiz', 'kjr', 'ksi'];

const decode = (s) =>
  s
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&#(\d+);/g, (_, n) => String.fromCharCode(Number(n)))
    .trim();

async function page(path) {
  const res = await fetch(BASE + path, { headers: { 'User-Agent': 'jaderka-rozvrh known-names updater' } });
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  const html = await res.text();
  return html.slice(html.indexOf('<main'));
}

const teachers = new Set();
for (const dept of DEPARTMENTS) {
  const html = await page(`/rozvrh/ucitele/${dept}`);
  for (const [, raw] of html.matchAll(/<summary[^>]*>\s*([^<]+?)\s*<\/summary>/g)) {
    // Drop notes such as "(Děčín)" and section headers such as "===== Externisté =====".
    const name = decode(raw).replace(/\s*\(.*\)\s*$/, '');
    if (name && !name.includes('=') && !name.includes('▾')) teachers.add(name);
  }
}

const rooms = new Set(['různé']);
const roomsHtml = await page('/seznam-uceben');
for (const [, row] of roomsHtml.matchAll(/<tr>(.*?)<\/tr>/gs)) {
  const cells = [...row.matchAll(/<td[^>]*>(.*?)<\/td>/gs)].map(([, c]) => decode(c.replace(/<[^>]+>/g, '')));
  const room = cells[1]?.replace(/\s*\(.*\)\s*$/, '');
  if (room) rooms.add(room);
}

const sorted = (set) => [...set].sort((a, b) => a.localeCompare(b, 'cs'));
const list = (items) => items.map((s) => `  ${JSON.stringify(s)},`).join('\n');
writeFileSync(
  new URL('../src/import/known-names.ts', import.meta.url),
  `// Generated by scripts/update-known-names.mjs from ${BASE} — do not edit by hand.
// Generated on ${new Date().toISOString().slice(0, 10)}.

/** Teachers listed on the department timetable pages (surname first). */
export const KNOWN_TEACHERS: readonly string[] = [
${list(sorted(teachers))}
];

/** Room codes as printed on the timetables ("Kód v rozvrhu"). */
export const KNOWN_ROOMS: readonly string[] = [
${list(sorted(rooms))}
];
`,
);
console.log(`${teachers.size} teachers, ${rooms.size} rooms`);
